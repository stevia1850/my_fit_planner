def estimate_meal(text: str) -> dict:
    raw = (text or "").strip()
    if not raw:
        return {"kcal": 0, "protein": 0, "hits": [], "note": "내용이 없습니다."}

    t = raw.replace(" ", "").lower()
    hits = []
    kcal = 0
    protein = 0
    used = set()
    for name, k, p, keys in FOODS:
        for key in keys:
            token = key.replace(" ", "").lower()
            if token and token in t and name not in used:
                hits.append(name)
                used.add(name)
                kcal += k
                protein += p
                break

    if not hits:
        # 못 알아보면 한 끼 평균치
        kcal, protein = 550, 22
        note = "음식을 특정하지 못해 일반 한 끼(약 550kcal, 단백질 22g)로 잡았습니다."
    else:
        note = "대략값입니다. 양에 따라 달라질 수 있어요. → " + ", ".join(hits)

    if any(x in t for x in ["많이", "2인", "두그릇", "두공기"]):
        kcal = int(kcal * 1.4)
        protein = int(protein * 1.3)
        note += " (양이 많아 보여 조금 올려 계산)"
    if any(x in t for x in ["조금", "반만", "간단히", "가볍게"]):
        kcal = int(kcal * 0.7)
        protein = int(protein * 0.8)
        note += " (가벼운 식사로 보고 낮춰 계산)"

    return {"kcal": int(kcal), "protein": int(protein), "hits": hits, "note": note}
