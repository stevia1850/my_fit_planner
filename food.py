def _match_one(piece: str):
    t = piece.replace(" ", "").lower()
    if not t:
        return None
    mul = 1.0
    if any(x in t for x in ["2개", "두개", "두조각", "2조각"]):
        mul = 2.0
    elif any(x in t for x in ["반", "조금", "슬라이스한장"]):
        mul = 0.5
    for name, k, p, keys in FOODS:
        keys_sorted = sorted(keys, key=len, reverse=True)
        for key in keys_sorted:
            token = key.replace(" ", "").lower()
            if token and token in t:
                return {
                    "raw": piece.strip(),
                    "name": name,
                    "kcal": int(round(k * mul)),
                    "protein": int(round(p * mul)),
                }
    return {
        "raw": piece.strip(),
        "name": "추정불가",
        "kcal": 80,
        "protein": 3,
    }


def estimate_meal(text: str) -> dict:
    raw = (text or "").strip()
    if not raw:
        return {"kcal": 0, "protein": 0, "hits": [], "items": [], "note": "쉼표로 음식을 나눠 적으세요."}

    parts = []
    for chunk in raw.replace("\n", ",").split(","):
        chunk = chunk.strip()
        if chunk:
            parts.append(chunk)

    items = []
    for piece in parts:
        found = _match_one(piece)
        if found:
            items.append(found)

    kcal = sum(i["kcal"] for i in items)
    protein = sum(i["protein"] for i in items)
    hits = [i["name"] for i in items]
    unknown = [i["raw"] for i in items if i["name"] == "추정불가"]
    note = "쉼표로 나눈 항목을 합산한 대략값입니다."
    if unknown:
        note += " 못 알아본 항목은 소량(80kcal)으로 잡음: " + ", ".join(unknown)
    return {"kcal": kcal, "protein": protein, "hits": hits, "items": items, "note": note}
